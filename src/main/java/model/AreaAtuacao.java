
package model;

public class AreaAtuacao {
    private Long idArea;
    private Long idCooperativa;
    private String municipioRegiao;


    public Long getIdArea() { return idArea; }

    public void setIdArea(Long idArea) { this.idArea = idArea; }

    public Long getIdCooperativa() { return idCooperativa; }

    public void setIdCooperativa(Long idCooperativa) { this.idCooperativa = idCooperativa; }

    public String getMunicipioRegiao() { return municipioRegiao; }

    public void setMunicipioRegiao(String municipioRegiao) { this.municipioRegiao = municipioRegiao; }
}
